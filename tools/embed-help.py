#!/usr/bin/env python3
# Turn a help folder into one C file. The app links that file and calls ui_help_open_files.
# The pages and pictures are then inside the program. Nothing is read from the card.
#
#   tools/embed-help.py examples/help build/help_pages.c help_pages
import os
import sys


def die(msg):
    sys.stderr.write("ERROR: %s\n" % msg)
    sys.exit(1)


def ident(name):
    if not name or name[0].isdigit():
        return False
    return all(c.isalnum() or c == "_" for c in name)


def main():
    if len(sys.argv) != 4:
        die("usage: embed-help.py DIR OUT.c SYMBOL")
    root, dest, symbol = sys.argv[1:]
    if not ident(symbol):
        die("symbol must be a C name: %s" % symbol)
    if not os.path.isdir(root):
        die("not a directory: %s" % root)
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for name in sorted(filenames):
            if name.startswith(".") or name == ".DS_Store":
                continue
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, root).replace(os.sep, "/")
            if rel.startswith("../") or rel == ".." or "/" not in rel and rel.startswith("."):
                continue
            with open(path, "rb") as fh:
                found.append((rel, fh.read()))
    found.sort(key=lambda item: item[0])
    os.makedirs(os.path.dirname(dest) or ".", exist_ok=True)
    with open(dest, "w", encoding="ascii") as out:
        out.write("/* Generated by tools/embed-help.py from %s. Do not edit. */\n" % root.replace("\\", "/"))
        out.write('#include "help.h"\n\n')
        for i, (rel, data) in enumerate(found):
            out.write("static const unsigned char %s_%d[] = {\n" % (symbol, i))
            for off in range(0, len(data), 16):
                chunk = data[off : off + 16]
                out.write("    " + ", ".join("%d" % b for b in chunk) + ",\n")
            if not data:
                out.write("    0\n")
            out.write("};\n\n")
        if not found:
            out.write("const struct ui_help_file %s[1] = {{0}};\n" % symbol)
            out.write("const int %s_count = 0;\n" % symbol)
            return
        out.write("const struct ui_help_file %s[] = {\n" % symbol)
        for i, (rel, data) in enumerate(found):
            escaped = rel.replace("\\", "\\\\").replace('"', '\\"')
            size = "sizeof %s_%d" % (symbol, i)
            if not data:
                size = "0"
            out.write('    { "%s", %s_%d, (int)%s },\n' % (escaped, symbol, i, size))
        out.write("};\n")
        out.write("const int %s_count = %d;\n" % (symbol, len(found)))


if __name__ == "__main__":
    main()
